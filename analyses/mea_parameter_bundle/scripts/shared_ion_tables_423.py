def read(path):
    if path.suffix == '.gz' or not path.is_file():
        archive = path if path.suffix == '.gz' else path.with_suffix('.json.gz')
        return json.loads(gzip.decompress(archive.read_bytes()))
    return json.loads(path.read_bytes())


